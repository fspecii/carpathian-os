#!/usr/bin/env python3
"""gen-folder-themes.py ICONS_DIR(containing Papirus) OUTDIR : one tiny icon theme per style and mode, Carpatic-<style>-<Light|Dark>, inheriting Papirus(-Light/-Dark)
with the folder colour of that style (what `papirus-folders -C <colour>` does, but as symlinks into the shared Papirus files, ~100 KB per theme).
Run at install time (needs papirus-icon-theme). Only symlinks and an index.theme are written: nothing of Papirus (GPL-3.0) is copied."""
import os, re, sys
COLOURS = {"macos": "breeze", "windows": "yellow", "ubuntu": "deeporange", "zen": "blue", "kylin": "paleorange", "carpatic": "teal", "nothing": "black"}
SIZES = ["22x22", "24x24", "32x32", "48x48", "64x64"]
src, out = sys.argv[1], sys.argv[2]
for style, col in COLOURS.items():
    for mode in ("Light", "Dark"):
        name = "Carpatic-%s-%s" % (style, mode); root = os.path.join(out, name)
        dirs = []
        for sz in SIZES:
            pdir = os.path.join(src, "Papirus", sz, "places")
            if not os.path.isdir(pdir): continue
            n = 0
            for f in sorted(os.listdir(pdir)):
                p = os.path.join(pdir, f)
                if not os.path.islink(p): continue
                tgt = os.readlink(p)
                m = re.match(r"^((?:folder|user)-)blue((?:-[a-z_-]+)?\.svg)$", tgt)
                if not m: continue
                new = m.group(1) + col + m.group(2)
                if not os.path.exists(os.path.join(pdir, new)): continue
                d = os.path.join(root, sz, "places"); os.makedirs(d, exist_ok=True)
                link = os.path.join(d, f)
                if os.path.lexists(link): os.remove(link)
                os.symlink("../../../Papirus/%s/places/%s" % (sz, new), link); n += 1
            if n: dirs.append(sz + "/places")
        with open(os.path.join(root, "index.theme"), "w") as fh:
            fh.write("[Icon Theme]\nName=%s\nComment=Papirus with the %s folder colour (%s), generated by Carpatic gtktheme\nInherits=Papirus-%s,Papirus\nDirectories=%s\n" % (name, style, col, mode, ",".join(dirs)))
            for d in dirs:
                sz = d.split("x")[0]
                fh.write("\n[%s]\nContext=Places\nSize=%s\nType=Fixed\n" % (d, sz))
